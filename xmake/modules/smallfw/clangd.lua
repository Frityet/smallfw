function write_config(output)
    output = output or path.join(os.projectdir(), ".clangd")
    local text = config_text()
    local old = os.isfile(output) and io.readfile(output) or nil
    os.mkdir(path.join(os.projectdir(), "build", ".clangd"))
    if old ~= text then
        io.writefile(output, text)
        print(".clangd updated")
    end
    return output
end

function clear_cache()
    os.rm(path.join(os.projectdir(), "build", ".clangd", "clang-module-cache"))
end

function source_files()
    local files = {}
    local seen = {}
    local roots = {
        "Runtime",
        "StandardLibrary",
        "benchmarking",
        "examples",
        path.join("tools", "generics-plugin"),
    }
    local suffixes = {"*.c", "*.h", "*.m", "*.mm", "*.cpp", "*.hpp"}
    for _, root in ipairs(roots) do
        for _, suffix in ipairs(suffixes) do
            for _, file in ipairs(os.files(path.join(root, "**", suffix))) do
                local normalized = file:gsub("\\", "/")
                if not seen[normalized] then
                    seen[normalized] = true
                    table.insert(files, normalized)
                end
            end
        end
    end
    table.sort(files)
    return files
end

function check_all(opt)
    opt = opt or {}
    write_config()
    if opt.clear_cache ~= false then
        clear_cache()
    end

    local clangd = find_program("clangd") or "clangd"
    local projectdir = os.projectdir()
    local failures = {}
    local files = source_files()
    for index, file in ipairs(files) do
        print("[%02d] clangd --check %s", index, file)
        local ok, errors = try {
            function ()
                os.runv(clangd, {
                    "--check=" .. file,
                    "--compile-commands-dir=" .. projectdir,
                    "--enable-config",
                    "--log=error",
                    "--tweaks=",
                })
                return true, nil
            end,
            catch {
                function (errors)
                    return false, errors
                end
            }
        }
        if not ok then
            table.insert(failures, string.format("%s: %s", file, tostring(errors)))
        end
    end

    if #failures > 0 then
        raise("clangd failed on %d file(s):\n%s", #failures, table.concat(failures, "\n"))
    end
    print("clangd checked %d file(s)", #files)
end
