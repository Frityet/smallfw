import("lib.detect.find_program")

local function _trim(value)
    return tostring(value or ""):gsub("^%s+", ""):gsub("%s+$", "")
end

local function _try_output(program, args)
    local ok, output = try {
        function ()
            return true, os.iorunv(program, args or {})
        end,
        catch {
            function ()
                return false, nil
            end
        }
    }
    if ok then
        return _trim(output)
    end
    return nil
end

local function _llvm_includedir()
    local candidates = {
        find_program("llvm-config"),
        find_program("llvm-config-22"),
        find_program("llvm-config-21"),
        "llvm-config",
    }
    for _, candidate in ipairs(candidates) do
        if candidate ~= nil and candidate ~= "" then
            local includedir = _try_output(candidate, {"--includedir"})
            if includedir ~= nil and includedir ~= "" and os.isdir(includedir) then
                return includedir
            end
        end
    end

    local dirs = os.dirs("/usr/lib/llvm-*/include")
    table.sort(dirs)
    for index = #dirs, 1, -1 do
        if os.isfile(path.join(dirs[index], "clang", "AST", "ASTConsumer.h")) then
            return dirs[index]
        end
    end
    return nil
end

local function _append(lines, ...)
    for _, line in ipairs({...}) do
        table.insert(lines, line)
    end
end

